import fs from "fs";
import https from "https";

const url = "https://restcountries.com/v3.1/all?fields=cca2,name,idd";

const data = await new Promise((resolve, reject) => {
  https
    .get(url, (res) => {
      let body = "";
      res.on("data", (c) => {
        body += c;
      });
      res.on("end", () => resolve(body));
    })
    .on("error", reject);
});

const countries = JSON.parse(data);
const byIso = new Map();
const allDials = [];

const NANP = new Set([
  "US", "CA", "AG", "AI", "AS", "BB", "BM", "BS", "DM", "DO", "GD", "GU", "JM", "KN", "KY", "LC",
  "MP", "MS", "PR", "SX", "TC", "TT", "VC", "VG", "VI",
]);

for (const c of countries) {
  const root = c.idd?.root?.replace("+", "");
  const suffixes = c.idd?.suffixes?.length ? c.idd.suffixes : [""];
  if (!root) continue;
  for (const suf of suffixes) {
    const dial = root + suf;
    if (dial && /^\d+$/.test(dial)) allDials.push(dial);
  }
  const dial = root + (suffixes[0] || "");
  if (!dial || !/^\d+$/.test(dial)) continue;
  if (!byIso.has(c.cca2)) {
    byIso.set(c.cca2, { iso2: c.cca2, name: c.name.common, dial });
  }
}

function lengths(iso2, dial) {
  if (iso2 === "PH") return { nationalMinLength: 10, nationalMaxLength: 10 };
  if (dial === "1" || NANP.has(iso2)) return { nationalMinLength: 10, nationalMaxLength: 10 };
  if (dial.length >= 3) return { nationalMinLength: 5, nationalMaxLength: 12 };
  return { nationalMinLength: 6, nationalMaxLength: 12 };
}

const list = [...byIso.values()].sort((a, b) => a.name.localeCompare(b.name));
const phIdx = list.findIndex((c) => c.iso2 === "PH");
if (phIdx > 0) {
  const [ph] = list.splice(phIdx, 1);
  list.unshift(ph);
}

const phoneCountries = list.map((c) => ({ ...c, ...lengths(c.iso2, c.dial) }));
const dialCodes = [...new Set(allDials)].sort((a, b) => b.length - a.length);

const content = `// Auto-generated by scripts/generate-phone-countries.mjs — run: node scripts/generate-phone-countries.mjs
import type { PhoneCountry } from "./phoneCountries";

export const ALL_PHONE_COUNTRIES: PhoneCountry[] = ${JSON.stringify(phoneCountries, null, 2)};

export const ALL_DIAL_CODES_SORTED: string[] = ${JSON.stringify(dialCodes)};
`;

fs.writeFileSync("lib/phoneCountryList.ts", content);
console.log(`Wrote ${phoneCountries.length} countries, ${dialCodes.length} dial codes`);
